#!/usr/bin/env bash
# Generates the per-app config files from .env.
#
#   cp .env.example .env      # then edit .env with your values
#   ./scripts/setup.sh
#
# Writes (both gitignored):
#   FieldCopilot/FieldCopilot/Secrets.xcconfig   — read by the iOS app at build time
#   FieldDispatcher/capella-config.json          — read by the macOS app at runtime
#
# Safe to re-run: it overwrites both files from whatever .env currently holds.

set -euo pipefail
cd "$(dirname "$0")/.."

if [[ ! -f .env ]]; then
  echo "error: no .env found."
  echo "       cp .env.example .env   then edit it, then re-run this script."
  exit 1
fi

python3 - <<'PY'
import json, pathlib, re, sys

env = {}
for line in pathlib.Path(".env").read_text().splitlines():
    line = line.strip()
    if not line or line.startswith("#") or "=" not in line:
        continue
    k, v = line.split("=", 1)
    env[k.strip()] = v.strip()

url  = env.get("SYNC_ENDPOINT_URL", "")
user = env.get("SYNC_USERNAME", "")
pwd  = env.get("SYNC_PASSWORD", "")
u_kyle = env.get("SYNC_USERNAME_KYLE", "")
p_kyle = env.get("SYNC_PASSWORD_KYLE", "")
u_bj   = env.get("SYNC_USERNAME_BJ", "")
p_bj   = env.get("SYNC_PASSWORD_BJ", "")
key  = env.get("OPENAI_API_KEY", "")

if not url:
    sys.exit("error: SYNC_ENDPOINT_URL is empty in .env")
if "YOUR-ID" in url:
    print("warning: SYNC_ENDPOINT_URL still contains the placeholder 'YOUR-ID' —")
    print("         sync will not connect until you set your real endpoint.")

# xcconfig treats '//' as the start of a comment, so everything after 'wss:'
# would be silently discarded. Splitting the slashes with an empty $()
# substitution keeps the URL intact.
xc_url = url.replace("://", ":/$()/", 1)

pathlib.Path("FieldCopilot/FieldCopilot").mkdir(parents=True, exist_ok=True)
pathlib.Path("FieldCopilot/FieldCopilot/Secrets.xcconfig").write_text(f"""\
// GENERATED by scripts/setup.sh from .env — do not commit, do not hand-edit.
// Edit .env and re-run ./scripts/setup.sh instead.
//
// NOTE: the $() below is an empty substitution that splits the '//' so the
// URL survives xcconfig comment parsing.

SYNC_ENDPOINT_URL = {xc_url}
SYNC_USERNAME = {user}
SYNC_PASSWORD = {pwd}

// Per-technician App Services accounts. Each demo tech signs in as
// themselves so App Services grants only that tech's channels.
SYNC_USERNAME_KYLE = {u_kyle}
SYNC_PASSWORD_KYLE = {p_kyle}
SYNC_USERNAME_BJ = {u_bj}
SYNC_PASSWORD_BJ = {p_bj}

OPENAI_API_KEY = {key}
""")

pathlib.Path("FieldDispatcher/capella-config.json").write_text(
    json.dumps({"endpointURL": url, "username": user, "password": pwd}, indent=2) + "\n"
)

print("✓ wrote FieldCopilot/FieldCopilot/Secrets.xcconfig")
print("✓ wrote FieldDispatcher/capella-config.json")
print()
print(f"  endpoint: {url}")
print(f"  user:     {user}")
print(f"  openai:   {'configured (cloud comparison enabled)' if key else 'not set (fully on-device)'}")
if u_kyle and u_bj:
    print(f"  per-user: {u_kyle} / {u_bj} (each tech syncs only their own work orders)")
else:
    print("  per-user: NOT set - both techs share one login, no isolation")
PY
